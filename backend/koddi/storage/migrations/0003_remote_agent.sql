CREATE TABLE IF NOT EXISTS agent_history (
 id INTEGER PRIMARY KEY, chat_id INTEGER NOT NULL REFERENCES chats(id) ON DELETE CASCADE,
 payload_json TEXT NOT NULL, created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS agent_history_chat ON agent_history(chat_id,id);
CREATE TABLE IF NOT EXISTS agent_plans (
 turn_id INTEGER PRIMARY KEY REFERENCES turns(id) ON DELETE CASCADE, steps_json TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS agent_requests (
 id INTEGER PRIMARY KEY, turn_id INTEGER NOT NULL REFERENCES turns(id) ON DELETE CASCADE,
 kind TEXT NOT NULL, payload_json TEXT NOT NULL, response_json TEXT,
 created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
