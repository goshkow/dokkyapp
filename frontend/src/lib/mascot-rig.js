  function clipFits(c,d){
    if(!c.when)return true;
    const m=d.getMonth(),day=d.getDate(),h=d.getHours();
    const newYear=(m===11&&day>=20)||(m===0&&day<=10);
    if(c.when==='night')return h>=22||h<6;
    if(c.when==='newyear')return newYear;
    if(c.when==='winter')return !newYear&&(m===11||m<=1);
    if(c.when==='spring')return m>=2&&m<=4;
    if(c.when==='summer')return m>=5&&m<=7;
    if(c.when==='autumn')return m>=8&&m<=10;
    return false;
  }
