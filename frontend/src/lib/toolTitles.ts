function computerTitles(args: Args): [string, string] {
  const command = String(args.command ?? '');
  const app = text(args.app, 32);
  const combo = text(args.combo, 24);
  const pair = COMPUTER[command] ?? ['Работаю с приложением{in}', 'Действие в приложении выполнено{in}'];
  const fill = (value: string) =>
    value
      .replace('{in}', app ? ` в ${app}` : '')
      .replace('{of}', app ? ` ${app}` : '')
      .replace('{app}', app || 'приложение')
      .replace('{combo}', combo || 'клавиши')
      .replace(/\s+/g, ' ')
      .trim();
  return [fill(pair[0]), fill(pair[1])];
}

/** Пара подписей для инструмента или undefined, если своего перевода нет. */
export function toolTitles(name: string, args: Args = {}): [string, string] | undefined {
  if (name === 'computer.use') return computerTitles(args);
  if (name === 'mcp.tool_call' && args.server) {
    const server = text(args.server, 32);
    return [`Вызываю инструмент ${server}`, `Инструмент ${server} выполнен`];
  }
  return STATIC[name];
}
